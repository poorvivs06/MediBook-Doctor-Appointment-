export const getLocalizedDoctor = (doctor, lang = "en") => {
  if (!doctor) return null;
  const loc = DOCTOR_TRANSLATIONS[doctor.id]?.[lang];
  if (!loc) return doctor;
  return {
    ...doctor,
    name: loc.name || doctor.name,
    specialty: loc.specialty || doctor.specialty,
    category: loc.category || doctor.category,
    experience: loc.experience || doctor.experience,
    hospital: loc.hospital || doctor.hospital,
    about: loc.about || doctor.about,
    availability: loc.availability || doctor.availability,
  };
};

export const getDoctorById = (id, lang = "en") => {
  if (!id) return null;
  const normalizedId = String(id).toLowerCase().trim();
  const found = doctors.find(
    (d) =>
      d.id.toLowerCase() === normalizedId ||
      d.name.toLowerCase().replace(/[^a-z0-9]/g, "") === normalizedId.replace(/[^a-z0-9]/g, "")
  ) || null;
  return found ? getLocalizedDoctor(found, lang) : null;
};
